"""Checks that the maths does what the README says, using made-up prices.

No internet is needed: every price here is generated by the test itself, with
sensitivities we choose, so we know the right answers in advance.

Run from the VS Code terminal, inside the project folder:
    Windows:  .venv\\Scripts\\python -m unittest discover tests
    Mac:      .venv/bin/python -m unittest discover tests
"""

import json
import tempfile
import unittest
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

from stress import historical, portfolio, scenarios

FACTORS = {
    "SPX": {"ticker": "IDX", "kind": "return", "label": "Stock index"},
    "UST10Y": {"ticker": "YLD", "kind": "yield", "label": "10-year yield"},
}
TRUE_BETAS = {                 # per decimal stock return, per bp of yield
    "STK": {"SPX": 1.20, "UST10Y": 0.0000},
    "BND": {"SPX": 0.00, "UST10Y": -0.0015},   # like a bond fund, duration 15
}
HOLDINGS = [
    {"ticker": "STK", "weight": 0.5, "asset_class": "Equities", "name": "Stocks"},
    {"ticker": "BND", "weight": 0.4, "asset_class": "Bonds", "name": "Bonds"},
    {"ticker": "CASH", "weight": 0.1, "asset_class": "Cash", "name": "Cash"},
]


def make_weekly_prices(weeks=300, seed=7, noise=1e-5):
    """Friday prices where each fund follows the factors with TRUE_BETAS."""
    rng = np.random.default_rng(seed)
    dates = pd.date_range("2019-01-04", periods=weeks, freq="W-FRI")
    idx_ret = rng.normal(0.002, 0.02, weeks)
    yld_chg_bp = rng.normal(0, 8, weeks) + 200 * idx_ret   # yields tend to fall when stocks fall
    idx = 100 * np.cumprod(1 + idx_ret)
    yld = 3.0 + np.cumsum(yld_chg_bp) / 100
    prices = {"IDX": idx, "YLD": yld}
    for ticker, b in TRUE_BETAS.items():
        r = b["SPX"] * idx_ret + b["UST10Y"] * yld_chg_bp + rng.normal(0, noise, weeks)
        prices[ticker] = 50 * np.cumprod(1 + r)
    frame = pd.DataFrame(prices, index=dates)
    frame.iloc[0, frame.columns.get_loc("STK")] = np.nan  # first move is undefined anyway
    return frame


class FactorModelTests(unittest.TestCase):
    def setUp(self):
        self.holdings = portfolio.load_portfolio(HOLDINGS, 1_000_000)
        self.prices = make_weekly_prices()
        self.model = scenarios.fit_factor_model(self.prices, self.holdings, FACTORS,
                                                lookback_years=10, frequency="W-FRI",
                                                min_weeks=52)

    def test_betas_are_recovered(self):
        for ticker, b in TRUE_BETAS.items():
            self.assertAlmostEqual(self.model.betas.loc[ticker, "SPX"], b["SPX"], places=3)
            self.assertAlmostEqual(self.model.betas.loc[ticker, "UST10Y"], b["UST10Y"], places=5)
            self.assertGreater(self.model.stats.loc[ticker, "r2"], 0.99)

    def test_isolated_moves_only_named_factor(self):
        shock = scenarios.shocks_in_model_units({"SPX": -8}, FACTORS)
        moves = scenarios.implied_factor_moves(shock, self.model.covariance, "isolated")
        self.assertAlmostEqual(moves["SPX"], -0.08)
        self.assertEqual(moves["UST10Y"], 0.0)

    def test_correlated_uses_conditional_expectation(self):
        shock = scenarios.shocks_in_model_units({"SPX": -8}, FACTORS)
        moves = scenarios.implied_factor_moves(shock, self.model.covariance, "correlated")
        cov = self.model.covariance
        expected = cov.loc["UST10Y", "SPX"] / cov.loc["SPX", "SPX"] * -0.08
        self.assertAlmostEqual(moves["UST10Y"], expected, places=8)
        self.assertLess(moves["UST10Y"], 0)  # our fake data: yields fall when stocks fall

    def test_scenario_portfolio_return_is_weighted_sum(self):
        run = scenarios.run_scenarios(self.holdings, self.model,
                                      [{"name": "Yields +100 bp", "shocks": {"UST10Y": 100}}],
                                      FACTORS, "isolated")
        bond_move = self.model.betas.loc["BND", "UST10Y"] * 100
        stock_move = self.model.betas.loc["STK", "UST10Y"] * 100
        expected = 0.4 * bond_move + 0.5 * stock_move
        self.assertAlmostEqual(run["summary"].loc["Yields +100 bp", "isolated_return"],
                               expected, places=8)
        self.assertAlmostEqual(bond_move, -0.15, places=3)

    def test_unknown_factor_is_a_clear_error(self):
        with self.assertRaises(portfolio.SettingsError):
            scenarios.shocks_in_model_units({"VIX": 10}, FACTORS)


class ReplayTests(unittest.TestCase):
    def setUp(self):
        self.holdings = portfolio.load_portfolio(HOLDINGS, 1_000_000)
        self.prices = make_weekly_prices()
        self.model = scenarios.fit_factor_model(self.prices, self.holdings, FACTORS, 10,
                                                "W-FRI", 52)

    def test_replay_matches_hand_calculation(self):
        start, end = self.prices.index[100], self.prices.index[120]
        regime = [{"name": "Test", "start": str(start.date()), "end": str(end.date())}]
        result = historical.replay_regimes(self.prices, self.holdings, regime, self.model,
                                           FACTORS)
        stk = self.prices.loc[end, "STK"] / self.prices.loc[start, "STK"] - 1
        bnd = self.prices.loc[end, "BND"] / self.prices.loc[start, "BND"] - 1
        expected = 0.5 * stk + 0.4 * bnd + 0.1 * 0.0
        self.assertAlmostEqual(result["summary"].loc["Test", "portfolio_return"], expected,
                               places=10)
        self.assertLessEqual(result["summary"].loc["Test", "max_drawdown"], 0)

    def test_missing_fund_is_estimated_and_flagged(self):
        prices = self.prices.copy()
        prices.loc[prices.index[:150], "BND"] = np.nan   # fund "launched" later
        start, end = prices.index[100], prices.index[120]
        regime = [{"name": "Early", "start": str(start.date()), "end": str(end.date())}]
        result = historical.replay_regimes(prices, self.holdings, regime, self.model, FACTORS)
        self.assertEqual(result["summary"].loc["Early", "estimated"], "BND")
        true_bnd = self.prices.loc[end, "BND"] / self.prices.loc[start, "BND"] - 1
        self.assertAlmostEqual(result["asset_returns"].loc["BND", "Early"], true_bnd, delta=0.01)


class PortfolioTests(unittest.TestCase):
    def test_weights_must_add_to_one(self):
        bad = [dict(h) for h in HOLDINGS]
        bad[0]["weight"] = 0.4
        with self.assertRaises(portfolio.SettingsError):
            portfolio.load_portfolio(bad, 100)

    def test_duplicate_ticker_rejected(self):
        bad = HOLDINGS + [dict(HOLDINGS[0])]
        with self.assertRaises(portfolio.SettingsError):
            portfolio.load_portfolio(bad, 100)


class ReportSmokeTest(unittest.TestCase):
    def test_outputs_are_written(self):
        from stress import report
        holdings = portfolio.load_portfolio(HOLDINGS, 1_000_000)
        prices = make_weekly_prices()
        model = scenarios.fit_factor_model(prices, holdings, FACTORS, 10, "W-FRI", 52)
        regime = [{"name": "Test", "start": str(prices.index[50].date()),
                   "end": str(prices.index[80].date()), "about": "Made up"}]
        hist = historical.replay_regimes(prices, holdings, regime, model, FACTORS)
        scen = scenarios.run_scenarios(holdings, model,
                                       [{"name": "Stocks -8%", "shocks": {"SPX": -8}}],
                                       FACTORS, "correlated")
        meta = {"summary_mode": "correlated", "last_price": prices.index[-1],
                "created": datetime.now(),
                "presets": [{"name": "Stocks -8%", "shocks": {"SPX": -8}}]}
        with tempfile.TemporaryDirectory() as tmp:
            paths = report.write_outputs(Path(tmp), holdings, hist, scen, model, FACTORS, meta)
            self.assertTrue(paths["html"].exists())
            self.assertTrue(paths["excel"].exists())
            page = paths["html"].read_text(encoding="utf-8")
            self.assertIn("Stocks -8%", page)

            # The slider section carries the model's numbers as data for the page.
            start = page.index('<script type="application/json" id="ex-data">')
            start = page.index(">", start) + 1
            data = json.loads(page[start:page.index("</script>", start)])
            bonds = next(h for h in data["holdings"] if h["ticker"] == "BND")
            self.assertAlmostEqual(bonds["betas"][1], model.betas.loc["BND", "UST10Y"])
            self.assertEqual(data["presets"][0]["name"], "Stocks -8%")


if __name__ == "__main__":
    unittest.main()
